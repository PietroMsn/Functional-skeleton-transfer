"""Comparison with the original 2021 implementation on the SMPL -> DFAUST example.

``tests/data/original_reference.npz`` holds the outputs of the original code,
generated by ``tools/make_original_reference.py``. These tests need the
example ``.mat`` files in ``data/`` (or in the folder named by the
``SKELETON_TRANSFER_DATA`` environment variable) and are skipped otherwise.
The full pipeline takes about two minutes.

What is expected to match:

- the Laplace-Beltrami spectra and the locality mask: exactly;
- the functional map pipeline: given the same regressor, the transferred
  joints agree within a few millimetres (FLANN, used originally, is an
  approximate nearest-neighbour search, and the initial map is now solved
  exactly instead of with Adam);
- the regressor: it is now the exact minimizer of the energy, so it differs
  from the original one (1000 Adam iterations did not converge: up to 2.6 cm
  of error on the source joints). The tests check that it is better, both on
  the energy and on the ground-truth joints of posed SMPL shapes.
"""

import os

import numpy as np
import pytest
from scipy.spatial.transform import Rotation

from skeleton_transfer import (
    FunctionalMapConfig, RegressorConfig, TransferConfig, load_smpl_source, load_target, transfer_skeleton,
)  # fmt: skip
from skeleton_transfer.regressor import regressor_energy
from skeleton_transfer.spectral import compute_laplace_basis

from .conftest import DATA_DIR, REFERENCE

SOURCE = os.path.join(DATA_DIR, "basicmodel_m_lbs.mat")
TARGET = os.path.join(DATA_DIR, "50007_knees_001806.mat")

pytestmark = pytest.mark.skipif(
    not (os.path.exists(SOURCE) and os.path.exists(TARGET) and os.path.exists(REFERENCE)),
    reason="example data or reference not available",
)


@pytest.fixture(scope="module")
def reference():
    return dict(np.load(REFERENCE))


@pytest.fixture(scope="module")
def run():
    source = load_smpl_source(SOURCE)
    target = load_target(TARGET)
    k = 120
    basis_src = compute_laplace_basis(source.vertices, source.faces, 400)
    basis_tgt = compute_laplace_basis(target.vertices, target.faces, 400)
    # The plain ZoomOut of the original method
    config = TransferConfig(functional_map=FunctionalMapConfig(bijective=False))
    result = transfer_skeleton(source, target, config, basis_src=basis_src)
    return dict(source=source, target=target, result=result, basis_src=basis_src, basis_tgt=basis_tgt, k=k)


def test_spectra_and_mask(run, reference):
    # The original clamps the first eigenvalue (~0) to 1e-6 in place.
    np.testing.assert_allclose(run["basis_src"].evals[:120], reference["evals_src"], rtol=1e-6, atol=2e-6)
    np.testing.assert_allclose(run["basis_tgt"].evals[:120], reference["evals_tgt"], rtol=1e-6, atol=2e-6)
    np.testing.assert_array_equal(run["result"].mask.astype(bool), reference["mask"])


def test_functional_map_matches_original(run, reference):
    """Same regressor + new functional map -> same joints as the original."""
    R = reference["regressor"].astype(float)
    result, k = run["result"], run["k"]
    spectral = (R @ run["basis_src"].evecs[:, :k]) @ result.C @ run["basis_tgt"].project(run["target"].vertices, k)
    pointwise = R @ run["target"].vertices[result.p2p]
    assert np.linalg.norm(spectral - reference["joints_spectral"], axis=1).max() < 3e-3
    assert np.linalg.norm(pointwise - reference["joints_pointwise"], axis=1).max() < 3e-3
    assert np.mean(result.p2p == reference["p2p"]) > 0.9


def test_regressor_improves_on_original(run, reference):
    source, R_new = run["source"], run["result"].regressor
    R_old = reference["regressor"].astype(float)
    cfg, mask = RegressorConfig(), run["result"].mask
    assert regressor_energy(R_new, source.vertices, source.joints, mask, cfg) < regressor_energy(
        R_old, source.vertices, source.joints, mask, cfg
    )
    np.testing.assert_allclose(R_new @ source.vertices, source.joints, atol=1e-8)


def _pose_smpl(source, rotvecs):
    """Linear blend skinning of the SMPL template (no pose blend shapes)."""
    J, P = source.joints, source.parents
    rots = Rotation.from_rotvec(rotvecs).as_matrix()
    G = np.zeros((len(J), 4, 4))
    for j in range(len(J)):
        T = np.eye(4)
        T[:3, :3] = rots[j]
        T[:3, 3] = J[j] - (J[P[j]] if j else 0)
        G[j] = T if j == 0 else G[P[j]] @ T
    posed_joints = G[:, :3, 3].copy()
    G[:, :3, 3] -= np.einsum("jab,jb->ja", G[:, :3, :3], J)  # relative to the rest pose
    verts_h = np.c_[source.vertices, np.ones(len(source.vertices))]
    posed_vertices = np.einsum("vj,jab,vb->va", source.skinning_weights, G, verts_h)[:, :3]
    return posed_vertices, posed_joints


def test_regressor_is_pose_invariant(run, reference):
    """On posed SMPL shapes the new regressor finds the true joints better."""
    source, R_new = run["source"], run["result"].regressor
    R_old = reference["regressor"].astype(float)
    rng = np.random.default_rng(0)
    err_new, err_old = [], []
    for _ in range(10):
        vertices, joints = _pose_smpl(source, rng.normal(0, 0.4, (len(source.joints), 3)))
        err_new.append(np.linalg.norm(R_new @ vertices - joints, axis=1))
        err_old.append(np.linalg.norm(R_old @ vertices - joints, axis=1))
    assert np.mean(err_new) < 0.5 * np.mean(err_old)
    assert np.mean(err_new) < 0.01  # metres
